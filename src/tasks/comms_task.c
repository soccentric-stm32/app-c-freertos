/**
 * @file    comms_task.c
 * @brief   HWLINK Comms task: COBS receive path, request dispatch and replies.
 * @details One task owns the whole USART3 protocol data path.  It drains the
 *          4 KB DMA ring, splits the byte stream on the COBS 0x00 delimiter,
 *          decodes and CRC-checks every frame, verifies every FlatBuffer with
 *          the flatcc verifier before use (COM-004), executes the DEMO request
 *          set and transmits exactly one reply per request (COM-003).  A
 *          request type the DEMO application does not implement is answered
 *          with a @c Nak UNSUPPORTED and changes no state (COM-005).
 *
 *          **Receive path.** @ref poll_receive reads the DMA ring,
 *          @ref feed_byte splits the stream into COBS bodies, then
 *          @ref hwlink_cobs_decode, @ref handle_raw and @ref handle_payload
 *          validate, de-duplicate and dispatch the request.  A frame rejected
 *          by the framing layer (bad COBS body, bad CRC, bad protocol major or
 *          reserved flag bits) is dropped silently (`LNK-004`), so line noise
 *          cannot be amplified into a NAK storm.
 *
 *          **Transmit path.** @ref send_body builds a @c hwlink_Message in the
 *          module-wide flatcc builder, copies the finished buffer into
 *          @ref build_payload and resets the builder; @ref send_payload then
 *          wraps it with @ref hwlink_build_raw, COBS-encodes it into
 *          @ref tx_frame and hands it to @ref app_uart3_send, which blocks
 *          until the last stop bit has left the shift register (DBT-005).
 *          Exactly one reply per accepted request is produced, and a reply is
 *          cached for replay only after it is on the wire.
 *
 *          **Replay cache (LNK-008).**  A repeated request sequence number
 *          resends the previous response without executing the request again.
 *          Only the most recent reply is kept; a new @c Hello clears the cache
 *          and requests with sequence number 0 are never cached.
 *
 *          **Queues (DRT-011).**  Two static FreeRTOS queues are owned here.
 *          The RX-hint queue only carries @c COMMS_EVT_RX hints from the UART
 *          ISR; ButtonEvents travel on a separate, shallow queue so that a
 *          burst of RX hints can never make the LED task wait (BTN-004,
 *          LED-006).  Buttons are debounced and rare, so the button queue is
 *          small and a full one drops the event instead of stalling the
 *          producer.
 *
 *          All buffers, the flatcc builder and both event queues are static, so
 *          the task allocates nothing after start-up (DRT-004).  A stopped
 *          receiver is re-armed instead of being treated as fatal, and the task
 *          checks in with the health task every 500 ms (COM-002, HLT-001).
 *
 *          About 14 KiB of static RAM is owned here: five
 *          @ref HWLINK_MAX_FRAME buffers (10 KiB) and two
 *          @ref HWLINK_MAX_ENCODED buffers (about 4 KiB), one of which is
 *          pinned in the non-cacheable DMA window.
 * @author  Sandesh Ghimire <sandesh@soccentric.com>
 * @date    2026-11-03
 * @target  STM32F767ZIT6
 * @srs     COM-001..COM-007, BTN-004, LED-006, section 8
 * @ingroup comms_task
 */

